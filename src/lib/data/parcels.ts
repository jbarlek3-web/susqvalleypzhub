function box(
  lat: number,
  lng: number,
  dLat = 0.0012,
  dLng = 0.0016,
): [number, number][] {
  return [
    [lat - dLat, lng - dLng],
    [lat - dLat, lng + dLng],
    [lat + dLat, lng + dLng],
    [lat + dLat, lng - dLng],
  ];
}

